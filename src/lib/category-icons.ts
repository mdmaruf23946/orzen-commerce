export const MAX_CATEGORY_ICONS = 3;

/** Legacy aliases so previously saved keys keep rendering. */
const LEGACY_ALIASES: Record<string, string> = {
  toys: "toy-brick",
  appliances: "refrigerator",
  book: "book-open",
  grocery: "shopping-basket",
  food: "utensils-crossed",
  phone: "smartphone",
  audio: "headphones",
  gaming: "gamepad-2",
  shoes: "footprints",
  beauty: "flower-2",
  pets: "paw-print",
  tools: "wrench",
  art: "palette",
  organic: "leaf",
  health: "pill",
};

function resolveKey(name: string): string {
  const k = name.trim();
  if (k in CATEGORY_ICONS) return k;
  return LEGACY_ALIASES[k] ?? k;
}

export function getCategoryIcon(name?: string | null): LucideIcon | null {
  if (!name) return null;
  const first = name.split(",")[0]?.trim();
  if (!first) return null;
  return CATEGORY_ICONS[resolveKey(first)] ?? null;
}

/** icon_name stores 1-3 comma-separated preset keys. */
export function parseIconNames(value?: string | null): string[] {
  if (!value) return [];
  return value
    .split(",")
    .map((s) => resolveKey(s))
    .filter((s) => s && s in CATEGORY_ICONS)
    .slice(0, MAX_CATEGORY_ICONS);
}

export function serializeIconNames(keys: string[]): string | null {
  const clean = keys.filter((k) => k in CATEGORY_ICONS).slice(0, MAX_CATEGORY_ICONS);
  return clean.length ? clean.join(",") : null;
}

export function searchIconKeys(keys: string[], query: string): string[] {
  const q = query.trim().toLowerCase().replace(/-/g, " ");
  if (!q) return keys;
  return keys.filter((k) => k.replace(/-/g, " ").includes(q));
}
