import { Link } from "@tanstack/react-router";

type Props = {
  title: string;
  html: string;
  storeName?: string | null;
  updatedAt?: string | null;
};

export function LegalPage({ title, html, storeName, updatedAt }: Props) {
  return (
    <div className="mx-auto max-w-3xl px-4 py-10 sm:px-6">
      <header className="mb-6 border-b pb-4">
        <h1 className="text-2xl font-bold sm:text-3xl">{title}</h1>
        {storeName && (
          <p className="mt-1 text-sm text-muted-foreground">{storeName}</p>
        )}
        {updatedAt && (
          <p className="mt-1 text-xs text-muted-foreground">
            Last updated: {new Date(updatedAt).toLocaleDateString()}
          </p>
        )}
      </header>
      <article
        className="prose prose-sm max-w-none sm:prose-base [&_a]:text-primary [&_h2]:mt-6 [&_h2]:text-lg [&_h2]:font-semibold [&_ol]:list-decimal [&_ol]:pl-5 [&_p]:my-3 [&_ul]:list-disc [&_ul]:pl-5"
        // Content is generated by trusted server templates only; user input is escaped upstream.
        dangerouslySetInnerHTML={{ __html: html }}
      />
      <footer className="mt-10 border-t pt-4 text-xs text-muted-foreground">
        <Link to="/" className="font-semibold text-sf-ink transition-colors hover:text-sf-accent">
          &larr; Back to store
        </Link>
      </footer>
    </div>
  );
}

